// Alvin Yang - unidentified flying thing
function setup() {
	createCanvas(800, 800);
  	background(220);
}
function draw() {
	strokeWeight(3)
	fill (0, 255, 0)
circle(150, 300, 150);
fill(255, 0, 0)
angleMode(DEGREES);
triangle (200, 200, 150, 350, 700, 550)
rotate(105);
strokeWeight (2);
rectMode(CENTER);
strokeWeight (5); 
fill (125,125,125)
rect (250, -300, 300, 130, 150);
}
